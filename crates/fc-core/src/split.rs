//! Splitting files that exceed the FAT32 4 GiB limit into raw chunks
//! (`name.ext.001`, `.002`… — the 7-Zip/HJSplit convention), with a JSON manifest,
//! a `.sha256` file and stand-alone join scripts so the file can be rebuilt
//! **without** Fast Copy (`copy /b` on Windows, `cat` on macOS/Linux).

use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

use crate::error::{IoContext, Result};

/// 4095 MiB: below FAT32's 4 GiB − 1 limit and a multiple of every cluster size ≤ 1 MiB.
pub const SPLIT_CHUNK: u64 = 4_293_918_720;
pub const MANIFEST_SUFFIX: &str = ".fcsplit.json";

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PartInfo {
    pub name: String,
    pub size: u64,
    pub sha256: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SplitManifest {
    pub format: u32,
    pub tool: String,
    pub original_name: String,
    pub total_size: u64,
    pub mtime_ms: i64,
    pub chunk_size: u64,
    pub parts: Vec<PartInfo>,
    /// SHA-256 of the whole original file.
    pub sha256: String,
}

pub fn part_name(original: &str, index: usize, count: usize) -> String {
    if count > 999 {
        format!("{original}.{:04}", index + 1)
    } else {
        format!("{original}.{:03}", index + 1)
    }
}

pub fn part_count(size: u64) -> usize {
    size.div_ceil(SPLIT_CHUNK).max(1) as usize
}

impl SplitManifest {
    pub fn manifest_name(original: &str) -> String {
        format!("{original}{MANIFEST_SUFFIX}")
    }

    pub fn load(path: &Path) -> Result<SplitManifest> {
        let data = std::fs::read(path).ctx("lecture du manifeste", path)?;
        serde_json::from_slice(&data).map_err(|e| {
            crate::error::Error::Other(format!("manifeste invalide « {} » : {e}", path.display()))
        })
    }

    /// Other files written next to the chunks.
    pub fn companion_files(&self) -> Vec<String> {
        vec![
            format!("{}.sha256", self.original_name),
            format!("JOIN-{}.cmd", self.original_name),
            format!("join-{}.sh", self.original_name),
        ]
    }

    /// Write manifest, `.sha256` and join scripts into `dir`. Returns the paths written.
    pub fn write_all(&self, dir: &Path) -> Result<Vec<PathBuf>> {
        let mut written = Vec::new();
        let mpath = dir.join(Self::manifest_name(&self.original_name));
        let json = serde_json::to_vec_pretty(self).expect("serialize manifest");
        write_durable(&mpath, &json)?;
        written.push(mpath);

        let shapath = dir.join(format!("{}.sha256", self.original_name));
        write_durable(
            &shapath,
            format!("{} *{}\n", self.sha256, self.original_name).as_bytes(),
        )?;
        written.push(shapath);

        // Windows: explicit part list (wildcard order is not guaranteed on FAT).
        let name = &self.original_name;
        let parts_cmd = self
            .parts
            .iter()
            .map(|p| format!("\"{}\"", p.name))
            .collect::<Vec<_>>()
            .join(" + ");
        let cmd = format!(
            "@echo off\r\n\
             rem Recolle « {name} » a partir de ses morceaux (genere par Fast Copy).\r\n\
             rem Rejoins « {name} » from its parts (generated by Fast Copy).\r\n\
             chcp 65001 >nul\r\n\
             cd /d \"%~dp0\"\r\n\
             if \"%~1\"==\"\" (set \"OUT=%~dp0{name}\") else (set \"OUT=%~1\\{name}\")\r\n\
             copy /b {parts_cmd} \"%OUT%\" || goto :err\r\n\
             echo Verification SHA-256 attendue / expected: {sha}\r\n\
             certutil -hashfile \"%OUT%\" SHA256\r\n\
             echo OK\r\n\
             pause\r\n\
             exit /b 0\r\n\
             :err\r\n\
             echo ERREUR / ERROR\r\n\
             pause\r\n\
             exit /b 1\r\n",
            sha = self.sha256
        );
        let cpath = dir.join(format!("JOIN-{name}.cmd"));
        write_durable(&cpath, cmd.as_bytes())?;
        written.push(cpath);

        let parts_sh = self
            .parts
            .iter()
            .map(|p| format!("'{}'", p.name.replace('\'', "'\\''")))
            .collect::<Vec<_>>()
            .join(" ");
        let qname = name.replace('\'', "'\\''");
        let sh = format!(
            "#!/bin/sh\n\
             # Recolle « {name} » a partir de ses morceaux (genere par Fast Copy).\n\
             # Usage : sh 'join-{qname}.sh' [dossier_de_sortie]\n\
             set -e\n\
             cd \"$(dirname \"$0\")\"\n\
             OUT=\"${{1:-.}}/{qname_dq}\"\n\
             cat {parts_sh} > \"$OUT\"\n\
             echo \"{sha} *$OUT\" | (shasum -a 256 -c - 2>/dev/null || sha256sum -c -)\n",
            qname_dq = name.replace('"', "\\\""),
            sha = self.sha256
        );
        let spath = dir.join(format!("join-{name}.sh"));
        write_durable(&spath, sh.as_bytes())?;
        written.push(spath);
        Ok(written)
    }
}

fn write_durable(path: &Path, data: &[u8]) -> Result<()> {
    let tmp = crate::util::temp_path(path);
    {
        let f = std::fs::File::create(&tmp).ctx("création", &tmp)?;
        use std::io::Write;
        (&f).write_all(data).ctx("écriture", &tmp)?;
        crate::sys::full_sync(&f).ctx("vidage", &tmp)?;
    }
    std::fs::rename(&tmp, path).ctx("renommage", path)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn names() {
        assert_eq!(part_name("a.iso", 0, 3), "a.iso.001");
        assert_eq!(part_count(SPLIT_CHUNK), 1);
        assert_eq!(part_count(SPLIT_CHUNK + 1), 2);
        const { assert!(SPLIT_CHUNK < 4_294_967_295) };
        assert_eq!(SPLIT_CHUNK % (1 << 20), 0);
    }
}
