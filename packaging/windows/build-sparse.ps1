<#
.SYNOPSIS
  Builds (and signs) the Fast Copy sparse package FastCopy.msix that gives the app a package
  identity, required by Windows 11 for the modern File Explorer context menu.

.DESCRIPTION
  The package only contains AppxManifest.xml + Assets\*.png. fast-copy.exe and
  fc_shellext_win.dll stay in the app install directory ("external location") which is passed
  at registration time: Add-AppxPackage -Path FastCopy.msix -ExternalLocation <installdir>
  (see register-sparse.ps1).

  Steps: stage manifest (Identity rewritten from parameters) -> MakeAppx pack /nv -> SignTool.

  Signing options (one of):
    -CertPath <pfx> [-CertPassword <pwd>]   sign with an existing PFX (Subject must equal -Publisher)
    -SelfSigned                             create/reuse a dev code-signing cert in Cert:\CurrentUser\My
                                            with Subject = -Publisher, export it to <OutDir>\FastCopy-dev.pfx/.cer
                                            and sign with it. To INSTALL a package signed that way, the .cer
                                            must be trusted machine-wide (admin, once):
                                              Import-Certificate -FilePath <OutDir>\FastCopy-dev.cer `
                                                -CertStoreLocation Cert:\LocalMachine\TrustedPeople
    -NoSign                                 produce an unsigned package (cannot be installed, CI signs later)
  Windows refuses to register an unsigned/untrusted package; the classic menu
  ("Show more options") keeps working without it.

.PARAMETER AppDir
  Optional app install dir / build output (folder containing fast-copy.exe and
  fc_shellext_win.dll). The script checks both files exist and copies FastCopy.msix into it,
  so the NSIS hook / register-sparse.ps1 find it next to the exe.

.EXAMPLE
  .\build-sparse.ps1 -SelfSigned -AppDir ..\..\target\release
.EXAMPLE
  .\build-sparse.ps1 -CertPath C:\secrets\codesign.pfx -CertPassword $env:PFX_PWD -Publisher "CN=My Company, O=My Company, C=FR" -Version 1.2.3
#>
[CmdletBinding()]
param(
    [string]$OutDir,
    [string]$AppDir,
    [string]$Version,
    [string]$Publisher = 'CN=Fast Copy',
    [string]$PackageName = 'FastCopy.ShellExtension',
    [ValidateSet('x64', 'arm64', 'x86', 'neutral')]
    [string]$Arch = 'x64',
    [string]$CertPath,
    [string]$CertPassword,
    [switch]$SelfSigned,
    [switch]$RemoveCertFromStore,
    [switch]$NoSign,
    [string]$TimestampUrl
)

$ErrorActionPreference = 'Stop'
# Windows PowerShell 5.1: $PSScriptRoot is empty inside param() defaults.
$ScriptDir = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
if (-not $OutDir) { $OutDir = Join-Path $ScriptDir 'out' }
Set-StrictMode -Version Latest

function Find-SdkTool([string]$name) {
    $cmd = Get-Command $name -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    $hostArch = if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64') { 'arm64' } else { 'x64' }
    $roots = @("${env:ProgramFiles(x86)}\Windows Kits\10\bin", "$env:ProgramFiles\Windows Kits\10\bin")
    foreach ($root in $roots) {
        if (-not (Test-Path $root)) { continue }
        $hit = Get-ChildItem $root -Directory -Filter '10.*' | Sort-Object { [version]$_.Name } -Descending |
            ForEach-Object { Join-Path $_.FullName "$hostArch\$name" } | Where-Object { Test-Path $_ } | Select-Object -First 1
        if ($hit) { return $hit }
    }
    throw "$name not found (install the Windows 10/11 SDK or put it on PATH)."
}

# ----- version (x.y.z -> x.y.z.0; MSIX needs 4 numeric parts) --------------------------------
if (-not $Version) {
    $cargo = Join-Path $PSScriptRoot '..\..\Cargo.toml'
    $m = Select-String -Path $cargo -Pattern '^\s*version\s*=\s*"([^"]+)"' | Select-Object -First 1
    $Version = if ($m) { $m.Matches[0].Groups[1].Value } else { '0.1.0' }
}
$Version = $Version.TrimStart('v') -replace '[-+].*$', ''
$parts = @($Version.Split('.') | ForEach-Object { [int]$_ })
while ($parts.Count -lt 4) { $parts += 0 }
$Version4 = ($parts[0..3] -join '.')

# ----- stage -----------------------------------------------------------------------------------
$OutDir = [IO.Path]::GetFullPath($OutDir)
$stage = Join-Path $OutDir 'stage'
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
New-Item -ItemType Directory -Force (Join-Path $stage 'Assets') | Out-Null
# Logos: the app's Tauri icons when present (app/src-tauri/icons, generated by `npm run icons`),
# otherwise the placeholders shipped in sparse\Assets.
$appIcons = Join-Path $PSScriptRoot '..\..\app\src-tauri\icons'
foreach ($logo in 'Square44x44Logo.png', 'Square150x150Logo.png', 'StoreLogo.png') {
    $src = Join-Path $appIcons $logo
    if (-not (Test-Path $src)) { $src = Join-Path $PSScriptRoot "sparse\Assets\$logo" }
    Copy-Item $src (Join-Path $stage "Assets\$logo")
}

[xml]$manifest = Get-Content -Raw -Encoding UTF8 (Join-Path $PSScriptRoot 'sparse\AppxManifest.xml')
$id = $manifest.Package.Identity
$id.Name = $PackageName
$id.Publisher = $Publisher
$id.Version = $Version4
$id.ProcessorArchitecture = $Arch
$manifestOut = Join-Path $stage 'AppxManifest.xml'
$settings = New-Object System.Xml.XmlWriterSettings
$settings.Encoding = New-Object System.Text.UTF8Encoding($false)
$settings.Indent = $true
$w = [System.Xml.XmlWriter]::Create($manifestOut, $settings)
$manifest.Save($w); $w.Close()

# ----- pack ------------------------------------------------------------------------------------
$makeappx = Find-SdkTool 'makeappx.exe'
$msix = Join-Path $OutDir 'FastCopy.msix'
Write-Host "MakeAppx: $makeappx"
& $makeappx pack /d $stage /p $msix /nv /o
if ($LASTEXITCODE -ne 0) { throw "MakeAppx failed ($LASTEXITCODE)" }

# ----- sign ------------------------------------------------------------------------------------
$createdThumbprint = $null
if ($SelfSigned) {
    $cert = Get-ChildItem Cert:\CurrentUser\My -CodeSigningCert |
        Where-Object { $_.Subject -eq $Publisher -and $_.NotAfter -gt (Get-Date).AddDays(7) } | Select-Object -First 1
    if (-not $cert) {
        Write-Host "Creating self-signed code-signing certificate '$Publisher' in Cert:\CurrentUser\My"
        $cert = New-SelfSignedCertificate -Type Custom -Subject $Publisher -KeyUsage DigitalSignature `
            -FriendlyName 'Fast Copy dev package signing' -CertStoreLocation 'Cert:\CurrentUser\My' `
            -TextExtension @('2.5.29.37={text}1.3.6.1.5.5.7.3.3', '2.5.29.19={text}') -NotAfter (Get-Date).AddYears(2)
        $createdThumbprint = $cert.Thumbprint
    }
    if (-not $CertPassword) { $CertPassword = 'fastcopy-dev' }
    $CertPath = Join-Path $OutDir 'FastCopy-dev.pfx'
    $sec = ConvertTo-SecureString -String $CertPassword -Force -AsPlainText
    Export-PfxCertificate -Cert $cert -FilePath $CertPath -Password $sec | Out-Null
    Export-Certificate -Cert $cert -FilePath (Join-Path $OutDir 'FastCopy-dev.cer') | Out-Null
    Write-Host "Dev certificate: thumbprint $($cert.Thumbprint)"
    Write-Host "  exported: $CertPath (password '$CertPassword') and $(Join-Path $OutDir 'FastCopy-dev.cer')"
}

if ($CertPath -and -not $NoSign) {
    $signtool = Find-SdkTool 'signtool.exe'
    $signArgs = @('sign', '/fd', 'SHA256', '/f', $CertPath)
    if ($CertPassword) { $signArgs += @('/p', $CertPassword) }
    if ($TimestampUrl) { $signArgs += @('/tr', $TimestampUrl, '/td', 'SHA256') }
    $signArgs += $msix
    Write-Host "SignTool: $signtool"
    & $signtool @signArgs
    if ($LASTEXITCODE -ne 0) { throw "SignTool failed ($LASTEXITCODE). Is the certificate Subject exactly '$Publisher'?" }
} elseif (-not $NoSign) {
    Write-Warning 'No certificate given (-CertPath / -SelfSigned): FastCopy.msix is UNSIGNED and cannot be registered as is.'
}

if ($createdThumbprint -and $RemoveCertFromStore) {
    # New-SelfSignedCertificate also drops a copy into Cert:\CurrentUser\CA (intermediate CAs).
    foreach ($store in 'My', 'CA') {
        $p = "Cert:\CurrentUser\$store\$createdThumbprint"
        if (Test-Path $p) { Remove-Item $p -Force }
    }
    Write-Host "Removed the dev certificate $createdThumbprint from Cert:\CurrentUser\My and \CA (the .pfx/.cer exports remain in $OutDir)."
}

# ----- copy next to the app --------------------------------------------------------------------
if ($AppDir) {
    $AppDir = [IO.Path]::GetFullPath($AppDir)
    foreach ($f in 'fast-copy.exe', 'fc_shellext_win.dll') {
        if (-not (Test-Path (Join-Path $AppDir $f))) { Write-Warning "$f not found in $AppDir (it must be there at registration time)." }
    }
    Copy-Item $msix $AppDir -Force
    Write-Host "Copied FastCopy.msix to $AppDir"
}

Write-Host "OK: $msix  (Name=$PackageName Publisher='$Publisher' Version=$Version4 Arch=$Arch)"
